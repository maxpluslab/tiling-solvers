"""``python.contact_dfs``: depth-first search over contacts, branching on one corner.

At every node the search looks at the corners of the part of the target that is
still uncovered. For each convex corner it asks the candidate generator which
placements fill it, takes the corner with the fewest, and tries each of those
placements in turn. ``docs/algorithms.md`` gives the rule and the argument that
it loses no assembly.

The state lives in ``_native.Assembly``; this module holds only the control
flow, with an explicit stack of frames in place of recursion.

What the search is and is not:

* Footprint regime only. Roofs are not looked at.
* It looks for exact assemblies. Pieces are put corner to corner, and "fits"
  means within the contact noise of the tolerance policy, which is far tighter
  than the tolerances a finished assembly is judged by.
* Assemblies that differ by exchanging congruent pieces, or by turning a piece
  onto itself, are found once. Assemblies that differ by a rotation of the
  whole tray are found separately.
* It is deterministic. The seed is not used.
"""

import time
from dataclasses import dataclass

from maxplus_solvers import _native
from maxplus_solvers.metrics import SearchMetrics
from maxplus_solvers.models import (
    Pose,
    PuzzleInstance,
    Regime,
    Solution,
    SolverConfig,
    SolveResult,
    SolveStatus,
    TolerancePolicy,
)
from maxplus_solvers.solvers import SolverSpec

NAME = "python.contact_dfs"
# Vertex-at-corner contacts with one edge flush, as generated by `Assembly.propose`.
CANDIDATE_SET = "corner-contact/1"

OPTIONS = frozenset({"node_limit"})


@dataclass(slots=True)
class _Frame:
    """One node of the search: the placements to try there, and how many have been tried."""

    candidates: list[_native.Candidate]
    tried: int = 0


def _branch(state: _native.Assembly) -> list[_native.Candidate]:
    """The placements for the convex corner that has the fewest. Ties go to the first corner."""
    best: list[_native.Candidate] | None = None
    for corner in state.frontier():
        if not corner.convex:
            continue
        candidates = state.propose(corner)
        if best is None or len(candidates) < len(best):
            best = candidates
            if not best:
                break
    return [] if best is None else best


def solve(instance: PuzzleInstance, config: SolverConfig) -> SolveResult:
    if instance.regime is not Regime.FOOTPRINT:
        raise ValueError(f"{NAME} works in the footprint regime, not {instance.regime}")
    unknown = sorted(set(config.options) - OPTIONS)
    if unknown:
        raise ValueError(f"{NAME}: unknown options {', '.join(unknown)}")
    node_limit = config.options.get("node_limit")
    if node_limit is not None and (
        isinstance(node_limit, bool) or not isinstance(node_limit, int) or node_limit < 1
    ):
        raise ValueError(f"{NAME}: node_limit must be a positive integer")

    policy = config.tolerances or TolerancePolicy.from_instance(instance)
    fit_mm = policy.contact_noise_mm
    if not fit_mm > 0:
        raise ValueError(f"{NAME}: the contact noise must be positive")
    # A turn by this angle moves a point one span away by the contact noise.
    fit_rad = fit_mm / instance.span_mm
    state = _native.Assembly(
        instance.target,
        [piece.polygon for piece in instance.pieces],
        length_tol=fit_mm,
        angle_tol=fit_rad,
        slope_tol=fit_rad,
    )

    metrics = SearchMetrics()
    solutions: list[Solution] = []
    started = time.perf_counter()
    cpu_started = time.process_time()
    exhausted = False

    frames: list[_Frame] = []
    descend = True
    while True:
        if descend:
            if node_limit is not None and metrics.nodes >= node_limit:
                break
            if (
                config.time_limit_s is not None
                and time.perf_counter() - started >= config.time_limit_s
            ):
                break
            metrics.nodes += 1
            metrics.max_depth = max(metrics.max_depth, len(frames))
            if state.all_placed:
                # Every piece is down. It is an assembly if nothing is left uncovered.
                if not state.frontier():
                    poses = {}
                    for index, piece in enumerate(instance.pieces):
                        pose = state.pose(index)
                        assert pose is not None
                        poses[piece.id] = Pose(*pose)
                    solutions.append(Solution(poses))
                    if metrics.first_solution_s is None:
                        metrics.first_solution_s = time.perf_counter() - started
                    if config.max_solutions is not None and len(solutions) >= config.max_solutions:
                        break
                else:
                    metrics.backtracks += 1
                candidates = []
            else:
                candidates = _branch(state)
                if not candidates:
                    metrics.backtracks += 1
            frames.append(_Frame(candidates))

        frame = frames[-1]
        if frame.tried > 0:
            state.undo()
        if frame.tried < len(frame.candidates):
            candidate = frame.candidates[frame.tried]
            frame.tried += 1
            state.place(candidate.piece, candidate.pose)
            metrics.placements += 1
            descend = True
        else:
            frames.pop()
            if not frames:
                exhausted = True
                break
            descend = False

    metrics.solutions = len(solutions)
    metrics.candidates_generated, metrics.rejected_outside, metrics.rejected_overlap, _ = (
        state.stats()
    )
    metrics.wall_time_s = time.perf_counter() - started
    if exhausted:
        metrics.exhausted_s = metrics.wall_time_s
    metrics.cpu_time_s = time.process_time() - cpu_started

    if solutions:
        status = SolveStatus.SOLVED
    elif exhausted:
        status = SolveStatus.NO_SOLUTION_FOUND
    else:
        status = SolveStatus.INTERRUPTED
    return SolveResult(
        status=status,
        solver=NAME,
        regime=instance.regime,
        instance_hash=instance.instance_hash(),
        solutions=tuple(solutions),
        exhaustive=exhausted,
        # The argument for the candidates is about exact assemblies in exact
        # arithmetic; this is f64 with tolerances. See docs/solver-contract.md.
        candidates_proven_complete=False,
        metrics=metrics.to_dict(),
        candidate_set=CANDIDATE_SET,
        config=config,
        solver_version=_native.version(),
    )


SPEC = SolverSpec(
    name=NAME,
    run=solve,
    candidate_sets={Regime.FOOTPRINT: CANDIDATE_SET},
    description="Python prototype: depth-first search over corner contacts, fewest first",
)
